CATEGORY_NOT_FOUND = "We couldn't find that category."


# --------------------------------------------------------------------------- URL rules


def media_url(path: str | None, settings: Settings) -> str | None:
    """``{PUBLIC_MEDIA_BASE}/{path}``; absolute URLs are returned unchanged."""
    if not path:
        return None
    if path.startswith(("http://", "https://", "//")):
        return path
    return f"{settings.public_media_base.rstrip('/')}/{path.lstrip('/')}"


def placeholder_url(kind: str, slug: str, settings: Settings) -> str:
    """``{PLACEHOLDER_BASE}/{kind}/{slug}.svg`` (generated by Django)."""
    return f"{settings.placeholder_base.rstrip('/')}/{kind}/{slug}.svg"


def product_image_url(product: Product, settings: Settings) -> str:
    first = next((image for image in product.images if image.image), None)
    return media_url(first.image if first else None, settings) or placeholder_url("product", product.slug, settings)


def image_url_for(path: str | None, product_slug: str, settings: Settings) -> str:
    """Image URL from a stored path, falling back to the product placeholder."""
    return media_url(path, settings) or placeholder_url("product", product_slug, settings)


def category_image_url(category: Category, settings: Settings) -> str:
    return media_url(category.image, settings) or placeholder_url("category", category.slug, settings)


# --------------------------------------------------------------------------- helpers


def parse_csv(value: str | None) -> list[str]:
    if not value:
        return []
    return [part.strip() for part in value.split(",") if part.strip()]


def parse_money(value: float | None) -> Decimal | None:
    if value is None:
        return None
    try:
        return Decimal(str(value))
    except InvalidOperation:
        return None


def active_variants(product: Product) -> list[ProductVariant]:
    return sorted(
        (variant for variant in product.variants if variant.is_active),
        key=lambda variant: (variant.sort_order, variant.weight_grams, variant.label),
    )


def is_sellable(product: Product) -> bool:
    return product.status == SELLABLE_PRODUCT_STATUS


def default_variant(variants: Sequence[ProductVariant]) -> ProductVariant | None:
    return next((variant for variant in variants if variant.is_default), variants[0] if variants else None)


def _as_str_list(value: object) -> list[str]:
    if not isinstance(value, list):
        return []
    return [str(item) for item in value if str(item).strip()]


def _nutrition(value: object) -> list[NutritionFact]:
    facts: list[NutritionFact] = []
    if isinstance(value, list):
        for entry in value:
            if isinstance(entry, dict) and entry.get("label"):
                facts.append(NutritionFact(label=str(entry["label"]), value=str(entry.get("value", ""))))
    return facts


def _lines(text: str | None) -> list[str]:
    return [line.strip(" -•\t") for line in (text or "").splitlines() if line.strip(" -•\t")]


# --------------------------------------------------------------------------- builders


class OfferContext:
    """Live offers loaded once per request, plus the ``now`` they were evaluated at."""

    def __init__(self, rules: Sequence[OfferRule], now: datetime) -> None:
        self.rules = list(rules)
        self.now = now

    @classmethod
    def load(cls, db: Session, now: datetime | None = None) -> "OfferContext":
        current = now or utcnow()
        return cls(offer_repository.live_rules(db, current), current)

    def price(self, price: Decimal, product_id: uuid.UUID, category_id: uuid.UUID) -> PricedUnit:
        return price_unit(Decimal(price), str(product_id), str(category_id), self.rules, self.now)

    def final_price(self) -> FinalPrice | None:
        """Callback for price sort/filter in the repository; ``None`` when no offer is live."""
        if not self.rules:
            return None
        return lambda price, product_id, category_id: self.price(price, product_id, category_id).final_price

    def hints(self, product_id: uuid.UUID, category_id: uuid.UUID) -> list[str]:
        rules = conditional_offers(str(product_id), str(category_id), self.rules, self.now)
        return list(dict.fromkeys(offer_hint(rule) for rule in rules))


def offer_out(rule: OfferRule | None, label: str | None) -> OfferOut | None:
    if rule is None:
        return None
    return OfferOut(id=uuid.UUID(str(rule.id)), name=rule.name, label=label or "", ends_at=rule.ends_at)


def build_variant(
    variant: ProductVariant, available: int, sellable: bool, priced: PricedUnit | None = None
) -> VariantOut:
    available_quantity = available if sellable else 0
    final_price = priced.final_price if priced is not None else variant.price
    return VariantOut(
        id=variant.id,
        sku=variant.sku,
        label=variant.label,
        weight_grams=variant.weight_grams or 0,
        mrp=money(variant.mrp),
        price=money(variant.price),
        discount_percent=discount_percent(variant.mrp, variant.price),
        in_stock=available_quantity > 0,
        available_quantity=available_quantity,
        final_price=money(final_price),
        offer_discount=money(priced.discount if priced is not None else 0),
        offer_discount_percent=priced.discount_percent if priced is not None else 0,
        offer=offer_out(priced.offer, priced.label) if priced is not None else None,
    )


def _card_fields(
    row: ProductRow, availability: dict[uuid.UUID, int], settings: Settings, offers: OfferContext
) -> dict:
    product = row.product
    variants = active_variants(product)
    sellable = is_sellable(product)
    priced = {variant.id: offers.price(variant.price, product.id, product.category_id) for variant in variants}
    variant_outs = [
        build_variant(variant, availability.get(variant.id, 0), sellable, priced[variant.id]) for variant in variants
    ]
    cheapest = min(variants, key=lambda variant: (variant.price, variant.sort_order)) if variants else None
    default = default_variant(variants)
    in_stock_outs = [variant for variant in variant_outs if variant.in_stock]
    return {
        "id": product.id,
        "slug": product.slug,
        "name": product.name,
        "short_description": product.short_description or "",
        "category": CategoryRef(id=product.category.id, name=product.category.name, slug=product.category.slug),
        "image_url": product_image_url(product, settings),
        "rating_avg": round(row.rating_avg, 1),
        "rating_count": row.rating_count,
        "tags": _as_str_list(product.tags),
        "is_featured": bool(product.is_featured),
        "is_bestseller": bool(product.is_bestseller),
        "in_stock": bool(in_stock_outs),
        "price_from": money(cheapest.price) if cheapest else 0.0,
        "mrp_from": money(cheapest.mrp) if cheapest else 0.0,
        "max_discount_percent": max((variant.discount_percent for variant in variant_outs), default=0),
        "default_variant_id": default.id if default else None,
        "variants": variant_outs,
        "final_price_from": min((v.final_price for v in (in_stock_outs or variant_outs)), default=0.0),
        "offer_label": priced[default.id].label if default else None,
        "offer_hints": offers.hints(product.id, product.category_id),
    }


def _availability_for(db: Session, rows: Iterable[ProductRow]) -> dict[uuid.UUID, int]:
    variant_ids = [variant.id for row in rows for variant in row.product.variants if variant.is_active]
    return catalog_repository.get_availability(db, variant_ids)


def build_cards(
    db: Session, rows: Sequence[ProductRow], settings: Settings, offers: OfferContext | None = None
) -> list[ProductCard]:
    """Cards for many products using a single availability query and a single offers load."""
    offers = offers or OfferContext.load(db)
    availability = _availability_for(db, rows)
    return [ProductCard(**_card_fields(row, availability, settings, offers)) for row in rows]


def build_detail(db: Session, row: ProductRow, settings: Settings) -> ProductDetail:
    product = row.product
    availability = _availability_for(db, [row])
    offers = OfferContext.load(db)
    images = [
        ProductImageOut(url=media_url(image.image, settings) or "", alt=image.alt_text or product.name)
        for image in product.images
        if image.image
    ]
    if not images:
        images = [ProductImageOut(url=placeholder_url("product", product.slug, settings), alt=product.name)]
    return ProductDetail(
        **_card_fields(row, availability, settings, offers),
        description=product.description or "",
        key_benefits=_lines(product.key_benefits),
        ingredients=product.ingredients or "",
        nutrition=_nutrition(product.nutrition),
        storage_info=product.storage_info or "",
        shelf_life=product.shelf_life or "",
        how_to_use=product.how_to_use or "",
        origin=product.origin or "",
        certifications=product.certifications or "",
        images=images,
        tax_rate=float(product.tax_rate or 0),
        seo_title=product.seo_title or product.name,
        seo_description=product.seo_description or product.short_description or "",
    )


def build_category(category: Category, product_count: int, settings: Settings) -> CategoryOut:
    return CategoryOut(
        id=category.id,
        name=category.name,
        slug=category.slug,
        short_description=category.short_description or "",
        description=category.description or "",
        image_url=category_image_url(category, settings),
        accent_color=category.accent_color or "#6F8F6A",
        is_featured=bool(category.is_featured),
        sort_order=category.sort_order or 0,
        product_count=product_count,
        seo_title=category.seo_title or category.name,
        seo_description=category.seo_description or category.short_description or "",
    )


# --------------------------------------------------------------------------- use cases


def list_products(
    db: Session, filters: ProductFilters, offset: int, limit: int, settings: Settings
) -> tuple[list[ProductCard], int]:
    offers = OfferContext.load(db)
    rows, total = catalog_repository.list_products(db, filters, offset, limit, final_price=offers.final_price())
    return build_cards(db, rows, settings, offers), total


def get_product_row(db: Session, slug_or_id: str) -> ProductRow:
    row = catalog_repository.get_product_row(db, slug_or_id)
    if row is None:
        raise NotFoundError(PRODUCT_NOT_FOUND)
    return row


def get_product_detail(db: Session, slug_or_id: str, settings: Settings) -> ProductDetail:
    return build_detail(db, get_product_row(db, slug_or_id), settings)


def related_products(db: Session, slug_or_id: str, settings: Settings, limit: int = 8) -> list[ProductCard]:
    row = get_product_row(db, slug_or_id)
    return build_cards(db, catalog_repository.related_rows(db, row.product, limit), settings)


def list_categories(db: Session, settings: Settings) -> list[CategoryOut]:
    return [build_category(category, count, settings) for category, count in catalog_repository.list_categories(db)]


def get_category(db: Session, slug: str, settings: Settings) -> CategoryOut:
    found = catalog_repository.get_category(db, slug)
    if found is None:
        raise NotFoundError(CATEGORY_NOT_FOUND)
    category, count = found
    return build_category(category, count, settings)


def get_filters(db: Session, q: str | None, categories: list[str]) -> ProductFiltersOut:
    facets = catalog_repository.category_facets(db, q)
    offers = OfferContext.load(db)
    low, high = catalog_repository.price_range(db, q, categories, final_price=offers.final_price())
    return ProductFiltersOut(
        categories=[CategoryFacet(slug=slug, name=name, count=count) for slug, name, count in facets],
        price=PriceRange(min=money(low), max=money(high)),
        weights=catalog_repository.weight_labels(db, q, categories),
        ratings=[4, 3, 2, 1],
    )
